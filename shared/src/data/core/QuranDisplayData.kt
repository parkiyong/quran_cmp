    fun getSuraName(
        sura: Int,
        wantPrefix: Boolean = false,
        wantTranslation: Boolean = false,
        useArabicNames: Boolean = false
    ): String {
        if (sura < QuranConstants.FIRST_SURA || sura > QuranConstants.LAST_SURA) return ""
        val base = if (useArabicNames) suraNamesArabic[sura - 1] else suraNamesTransliterated[sura - 1]
        val prefixed = if (wantPrefix) {
            if (useArabicNames) "سورة $base" else "Surah $base"
        } else base
        return if (wantTranslation && !useArabicNames) {
            val tr = suraNamesTranslation.getOrNull(sura - 1).orEmpty()
            if (tr.isNotBlank()) "$prefixed ($tr)" else prefixed
        } else {
            prefixed
        }
    }

    fun getSuraTranslation(sura: Int): String =
        suraNamesTranslation.getOrNull(sura - 1).orEmpty()

    fun getSuraArabicName(sura: Int): String =
        suraNamesArabic.getOrNull(sura - 1).orEmpty()

    fun getSuraNameFromPage(quranInfo: QuranInfo, page: Int): String =
        getPageHeaderTitle(quranInfo, page)

    fun getPageSubtitle(quranInfo: QuranInfo, page: Int): String =
        "Page $page • ${getJuzDisplayString(quranInfo, page)}"

    fun getSuraArabicTitle(sura: Int): String {
        if (sura < QuranConstants.FIRST_SURA || sura > QuranConstants.LAST_SURA) return ""
        return "سورة ${suraNamesArabic[sura - 1]}"
    }

    fun getQuarterPrefix(quarterIndex: Int): String {
        return quarterPrefixArray.getOrNull(quarterIndex).orEmpty()
    }

    fun getSuraListMetaString(quranInfo: QuranInfo, sura: Int): String {
        val type = if (quranInfo.isMakki(sura)) "Makki" else "Madani"
        val ayahs = quranInfo.getNumberOfAyahs(sura)
        val versesLabel = if (ayahs == 1) "1 verse" else "$ayahs verses"
        return "$type - $versesLabel"
    }

    fun getPageHeaderTitle(quranInfo: QuranInfo, page: Int): String {
        if (!quranInfo.isValidPage(page)) return ""
        val bounds = quranInfo.getPageBounds(page)
        return (bounds[0]..bounds[2]).joinToString(", ") {
            getSuraName(it, wantPrefix = true)
        }
    }

    fun getJuzDisplayString(quranInfo: QuranInfo, page: Int): String {
        val juz = quranInfo.getJuzForDisplayFromPage(page)
        val rub3 = quranInfo.getRub3FromPage(page)
        val hizbPart = if (rub3 >= 0) {
            val hizb = (rub3 / 4) + 1
            val rem = rub3 % 4
            when (rem) {
                1 -> " • ¼ Hizb $hizb"
                2 -> " • ½ Hizb $hizb"
                3 -> " • ¾ Hizb $hizb"
                else -> " • Hizb $hizb"
            }
        } else ""
        return "Juzʼ $juz$hizbPart"
    }

    fun toArabicNumber(n: Int): String {
        val arabicDigits = charArrayOf('٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩')
        return n.toString().map { ch ->
            if (ch in '0'..'9') arabicDigits[ch - '0'] else ch
        }.joinToString("")
    }

    private val arabicDiacriticsRegex = Regex("[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]")

    fun normalizeArabicForSearch(input: String): String {
        val withoutDiacritics = arabicDiacriticsRegex.replace(input, "")
        val sb = StringBuilder(withoutDiacritics.length)
        for (ch in withoutDiacritics) {
            val norm = when (ch) {
                'أ', 'إ', 'آ', 'ٱ' -> 'ا'
                'ة' -> 'ه'
                'ى' -> 'ي'
                'ؤ' -> 'و'
                'ئ' -> 'ي'
                else -> ch
            }
            sb.append(norm)
        }
        return sb.toString()
    }
